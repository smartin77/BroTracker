"""Generate/check Q32.32 equal-temperament constants using exact Python integers.

No floating point or numerical library: y**12 = 2**(384 + semitones).
Binary search finds floor(y); compare the exact half-integer's twelfth power
against the target to round to nearest, ties upward. All octave entries are exact.
Run from repository root: python tools/generate_note_playback_steps.py --check
Without --check, rewrite only the generated constants header.
"""
from pathlib import Path
import argparse

OUTPUT = Path(__file__).resolve().parents[1] / 'src/core/audio/note_playback_steps.h'

def quantize(interval):
    target = 1 << (384 + interval)
    low, high = 0, 1 << 42
    while low + 1 < high:
        middle = (low + high) // 2
        if middle ** 12 <= target:
            low = middle
        else:
            high = middle
    return low + int((target << 12) >= (2 * low + 1) ** 12)

def generated():
    values = [quantize(i) for i in range(-103, 104)]
    lines = [', '.join(str(v) + 'ULL' for v in values[i:i+6]) for i in range(0, len(values), 6)]
    return ('#pragma once\n#include <cstdint>\nnamespace BroTracker { namespace Detail {\n'
            '// Generated by tools/generate_note_playback_steps.py; do not hand edit.\n'
            '// Exact integer twelfth-root quantization, nearest Q32.32, ties upward.\n'
            '// Indexed by semitone interval + 103; [-103,103].\n'
            'inline constexpr std::uint64_t kNotePlaybackSteps[207] = {\n    ' +
            ',\n    '.join(lines) + '\n};\n} }\n')

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generated()
    if args.check:
        if OUTPUT.read_text(encoding='utf-8') != text:
            raise SystemExit('Generated note step constants differ')
        print('All 207 checked-in note step constants match exact generation')
    else:
        OUTPUT.write_text(text, encoding='utf-8')

if __name__ == '__main__':
    main()
